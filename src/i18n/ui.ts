export function t(lang: Lang, path: string): string {
  const keys = path.split('.');
  let node: any = ui[lang];
  for (const k of keys) {
    if (node && typeof node === 'object' && k in node) node = node[k];
    else return path;
  }
  return typeof node === 'string' ? node : path;
}
